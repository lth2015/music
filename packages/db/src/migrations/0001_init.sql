-- LOOPSCENE initial schema — MySQL 8.0 / Aurora MySQL 3.x.
--
-- Statements are separated by a line containing exactly `-- ;;`. MySQL DDL is
-- implicitly committed, so the runner sends one statement at a time; a trigger
-- body contains its own semicolons, which is why a plain `;` split will not do.
--
-- Design rules enforced here rather than in application code:
--   * every business object names its owner, so ownership checks cannot be
--     forgotten at the query site (SEC-01);
--   * JPY amounts are integers (§10);
--   * timestamps are DATETIME(3) holding UTC, rendered JST in the UI;
--   * audio blobs never live in the database — only storage keys and hashes;
--   * the credit ledger is append-only and the derived per-batch counters carry
--     CHECK constraints (enforced from 8.0.16), so an over-sell is a database
--     error rather than a silently negative balance (§6.2, GEN-03).
--
-- Ids are CHAR(36) ascii UUIDs generated by the application: MySQL has no
-- RETURNING, and generating the id up front avoids a read-back race.

CREATE TABLE users (
  id                CHAR(36) CHARACTER SET ascii NOT NULL,
  -- Cognito `sub` in integration/production; a deterministic local id in demo.
  external_id       VARCHAR(255)  NOT NULL,
  auth_provider     VARCHAR(32)   NOT NULL,
  email             VARCHAR(320)  NOT NULL,
  display_name      VARCHAR(120)  NULL,
  role              VARCHAR(16)   NOT NULL DEFAULT 'user',
  status            VARCHAR(16)   NOT NULL DEFAULT 'active',
  age_confirmed_at  DATETIME(3)   NULL,
  terms_accepted_at DATETIME(3)   NULL,
  -- SEC-11 / UI-02: marketing consent is separate from account use, default off.
  marketing_opt_in  TINYINT(1)    NOT NULL DEFAULT 0,
  created_at        DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at        DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  deleted_at        DATETIME(3)   NULL,
  -- MySQL has no partial indexes. A generated column that is NULL for deleted
  -- rows gives the same effect, because a unique index ignores NULLs.
  email_active      VARCHAR(320) GENERATED ALWAYS AS
                      (CASE WHEN deleted_at IS NULL THEN email END) STORED,
  PRIMARY KEY (id),
  UNIQUE KEY users_provider_subject_uk (auth_provider, external_id),
  UNIQUE KEY users_email_active_uk (email_active),
  CONSTRAINT users_role_chk   CHECK (role IN ('user','support','admin')),
  CONSTRAINT users_status_chk CHECK (status IN ('active','suspended','deleted'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci
-- ;;

