-- Immutability guard: only `status` and `status_reason` may ever change, so a
-- new commercial agreement cannot retroactively overwrite the terms a user
-- generated under (SEC-08).
CREATE TRIGGER license_snapshots_freeze
BEFORE UPDATE ON license_snapshots
FOR EACH ROW
BEGIN
  IF NEW.track_id            <=> OLD.track_id            = 0
  OR NEW.user_id             <=> OLD.user_id             = 0
  OR NEW.provider_id         <=> OLD.provider_id         = 0
  OR NEW.provider_model      <=> OLD.provider_model      = 0
  OR NEW.contract_version    <=> OLD.contract_version    = 0
  OR NEW.license_version     <=> OLD.license_version     = 0
  OR NEW.territory           <=> OLD.territory           = 0
  OR NEW.source_sha256       <=> OLD.source_sha256       = 0
  OR NEW.generated_at        <=> OLD.generated_at        = 0
  OR NEW.commercial_delivery <=> OLD.commercial_delivery = 0
  OR CAST(NEW.allowed_uses AS CHAR)    <=> CAST(OLD.allowed_uses AS CHAR)    = 0
  OR CAST(NEW.prohibited_uses AS CHAR) <=> CAST(OLD.prohibited_uses AS CHAR) = 0
  THEN
    SIGNAL SQLSTATE '45000'
      SET MESSAGE_TEXT = 'license_snapshots are immutable except status/status_reason';
  END IF;
END
-- ;;

